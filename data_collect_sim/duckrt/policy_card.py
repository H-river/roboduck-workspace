"""Policy cards: one YAML per ONNX policy describing exactly how to run it.

Cards are generated by scripts/make_policy_cards.py from the training configs; the
values carry their source as YAML comments. This module only reads them (and updates
the few fields that tests fill in, e.g. `validated_on`, `handoff`, `duration_s`).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import yaml

from duckrt.config import CONFIG_DIR, resolve

CARD_DIR = CONFIG_DIR / "policies"


@dataclass
class PolicyCard:
    name: str
    onnx: Path
    control_hz: float
    obs_layout: list[dict[str, Any]]
    obs_history: int
    obs_scales: dict[str, float]
    action: dict[str, Any]
    joint_names: list[str]
    default_q: np.ndarray
    command_range: dict[str, list[float]]
    command_rules: dict[str, Any]
    validated_on: str
    handoff: dict[str, Any]
    duration_s: float | None
    sim: dict[str, Any]
    task: dict[str, Any] = field(default_factory=dict)
    path: Path | None = None

    @property
    def obs_dim(self) -> int:
        return int(sum(t["dim"] for t in self.obs_layout))

    @property
    def action_scale(self) -> float:
        return float(self.action["scale"])


def load_card(name_or_path: str | Path) -> PolicyCard:
    p = Path(name_or_path)
    if not p.suffix:
        p = CARD_DIR / f"{name_or_path}.yaml"
    p = resolve(p)
    with open(p) as f:
        d = yaml.safe_load(f)
    return PolicyCard(
        name=d["name"],
        onnx=resolve(d["onnx"]),
        control_hz=float(d["control_hz"]),
        obs_layout=list(d["obs_layout"]),
        obs_history=int(d["obs_history"]),
        obs_scales={k: float(v) for k, v in (d.get("obs_scales") or {}).items()},
        action=dict(d["action"]),
        joint_names=list(d["joint_names"]),
        default_q=np.asarray(d["default_q"], dtype=np.float64),
        command_range={k: [float(x) for x in v] for k, v in d["command_range"].items()},
        command_rules=dict(d.get("command_rules") or {}),
        validated_on=str(d.get("validated_on", "")),
        handoff=dict(d.get("handoff") or {}),
        duration_s=None if d.get("duration_s") is None else float(d["duration_s"]),
        sim=dict(d.get("sim") or {}),
        task=dict(d.get("task") or {}),
        path=p,
    )


def update_card_fields(path: str | Path, updates: dict[str, Any]) -> None:
    """Rewrite top-level scalar / flow-mapping fields in place, keeping comments.

    Only for fields written on one line by make_policy_cards.py (validated_on, handoff,
    duration_s). Each value is emitted as YAML flow style.
    """
    p = resolve(path)
    text = p.read_text()
    for key, value in updates.items():
        dumped = yaml.safe_dump(value, default_flow_style=True, allow_unicode=True, width=10_000).strip()
        if dumped.endswith("\n..."):
            dumped = dumped[:-4].strip()
        pattern = re.compile(rf"^{re.escape(key)}:.*$", re.MULTILINE)
        if not pattern.search(text):
            raise KeyError(f"{key} not found in {p}")
        text = pattern.sub(lambda _m: f"{key}: {dumped}", text, count=1)
    p.write_text(text)
